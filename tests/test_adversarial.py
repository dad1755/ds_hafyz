# ------------------------------------------------- 2. upload size, exact boundary
def _seed_csv_bytes(rows: int = 1) -> bytes:
    """The real seed file's header plus the requested number of data rows."""
    seed = REPO / "data" / "UCI_Credit_Card.csv"
    lines = seed.read_bytes().splitlines(keepends=True)
    return b"".join(lines[: rows + 1])


def test_the_size_limit_is_the_documented_ten_mebibytes():
    assert validation.MAX_UPLOAD_BYTES == 10 * 1024 * 1024


def test_a_payload_of_exactly_the_limit_is_accepted_and_one_byte_more_is_refused():
    payload = _seed_csv_bytes()

    at_limit = validation.validate_csv_bytes(payload, max_bytes=len(payload))
    assert at_limit.ok, at_limit.messages()

    one_under = validation.validate_csv_bytes(payload, max_bytes=len(payload) - 1)
    assert not one_under.ok
    assert one_under.codes == {"file_too_large"}
    assert str(len(payload)) in one_under.messages()[0]


def test_quarantine_holds_the_same_boundary(tmp_path):
    payload = _seed_csv_bytes()
    stored = validation.quarantine_upload(
        payload, "seed.csv", quarantine_dir=tmp_path / "q", max_bytes=len(payload)
    )
    assert stored.size_bytes == len(payload)

    with pytest.raises(validation.ValidationError) as refused:
        validation.quarantine_upload(
            payload + b"x", "seed.csv", quarantine_dir=tmp_path / "q2", max_bytes=len(payload)
        )
    assert refused.value.code == "file_too_large"
    assert not (tmp_path / "q2").exists(), "an oversize payload is never written at all"


def test_an_oversize_stage_upload_is_recorded_and_leaves_no_file(
    conn, admin_id, tmp_path
):
    token = _admin_token(conn)
    quarantine = tmp_path / "quarantine"
    with pytest.raises(data_manager.DatasetRejected) as rejected:
        data_manager.stage_upload(
            conn,
            token,
            _seed_csv_bytes(),
            "seed.csv",
            quarantine_dir=quarantine,
            max_bytes=64,
        )
    assert rejected.value.report.codes == {"file_too_large"}
    assert list(quarantine.glob("*")) == []
    assert conn.execute("SELECT COUNT(*) AS n FROM dataset_versions").fetchone()["n"] == 0


# ----------------------------------------------------- 3. quarantine containment
def test_an_uploaded_name_cannot_escape_the_quarantine_directory(tmp_path):
    quarantine = tmp_path / "q"
    for hostile in (
        "../../etc/passwd",
        "..\\..\\windows\\system32\\cfg",
        "/etc/shadow",
        "....//....//etc/passwd.csv",
        "\x00.csv",
    ):
        stored = validation.quarantine_upload(b"a,b\n1,2\n", hostile, quarantine_dir=quarantine)
        assert stored.path.parent == quarantine.resolve()
        assert stored.path.name == stored.generated_filename
        assert ".." not in stored.path.name
        assert stored.original_filename_safe.count("/") == 0
        assert stored.original_filename_safe.count("\\") == 0
        assert stored.original_filename_safe.endswith(".csv")


def test_a_quarantined_file_is_generated_owner_only_and_not_named_after_the_upload(tmp_path):
    stored = validation.quarantine_upload(
        b"a,b\n1,2\n", "UCI_Credit_Card.csv", quarantine_dir=tmp_path / "q"
    )
    assert stored.generated_filename != "UCI_Credit_Card.csv"
    assert re.fullmatch(r"\d{8}T\d{6}Z-[0-9a-f]{12}\.csv", stored.generated_filename)
    mode = stat.S_IMODE(stored.path.stat().st_mode)
    assert mode == 0o600, f"quarantined upload is mode {oct(mode)}, expected 0o600"


# --------------------------------------------- 4. secret patterns in shipped files
def _check_no_secrets_module():
    path = REPO / "scripts" / "check_no_secrets.py"
    spec = importlib.util.spec_from_file_location("check_no_secrets", path)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def _shipped_files() -> list[Path]:
    files = [REPO / "app.py", REPO / "compose.yaml", REPO / "Dockerfile",
             REPO / "requirements.txt", REPO / "requirements.in", REPO / ".env.example",
             REPO / ".streamlit" / "config.toml"]
    for directory in ("src", "ml", "scripts"):
        files.extend(sorted((REPO / directory).rglob("*.py")))
    files.extend(sorted((REPO / "models").glob("*.json")))
    return [path for path in files if path.is_file()]


def test_no_credential_pattern_appears_in_any_shipped_file():
    patterns = _check_no_secrets_module().PATTERNS
    findings: list[str] = []
    for path in _shipped_files():
        blob = path.read_bytes()
        for label, pattern in patterns:
            if pattern.search(blob):
                findings.append(f"{label} in {path.relative_to(REPO)}")
    assert findings == [], findings


def test_no_shipped_file_carries_a_real_password_hash():
    """The only hash-shaped string allowed is the algorithm marker in ``src/security.py``.

    A full argon2 record (``$argon2id$v=…$m=…,t=…,p=…$salt$digest``) is a credential
    equivalent and must never be committed, in a fixture or anywhere else.
    """
    record = re.compile(
        rb"\$argon2(?:id|i|d)\$v=\d+\$m=\d+,t=\d+,p=\d+\$[A-Za-z0-9+/]{10,}\$[A-Za-z0-9+/]{10,}"
    )
    offenders = [
        str(path.relative_to(REPO))
        for path in _shipped_files()
        if record.search(path.read_bytes())
    ]
    assert offenders == [], offenders


def test_env_example_carries_placeholders_only():
    """Every credential-shaped variable in the example file is a placeholder."""
    text = (REPO / ".env.example").read_text(encoding="utf-8")
    secret_names = re.compile(r"(PASSWORD|TOKEN|SECRET|API_KEY|PRIVATE_KEY)", re.IGNORECASE)
    checked = 0
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, value = stripped.split("=", 1)
        value = value.strip().strip('"').strip("'")
        if not secret_names.search(key):
            continue
        checked += 1
        assert value.upper().startswith(("REPLACE", "CHANGE", "YOUR_", "<")) or value.startswith(
            "${"
        ), f"{key.strip()} in .env.example looks like a real value"
    assert checked >= 3, "the example must still document every credential variable"


