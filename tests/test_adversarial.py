# ------------------------------------------------------- 6. no credential in a log
def test_no_password_token_or_hash_reaches_the_process_log(conn, admin_id, user_id, caplog):
    service = load_service()
    with caplog.at_level(logging.DEBUG):
        with pytest.raises(security.InvalidCredentials):
            security.login(conn, "admin_one", "definitely-not-the-password")
        principal, token = security.login(conn, "demo_user", USER_PASSWORD)
        security.change_password(conn, token, USER_PASSWORD, NEW_PASSWORD)
        _, fresh = security.login(conn, "demo_user", NEW_PASSWORD)
        predictions.submit_prediction(
            conn,
            fresh,
            service,
            {
                "LIMIT_BAL": 50000, "SEX": 2, "EDUCATION": 2, "MARRIAGE": 2, "AGE": 35,
                "PAY_0": 0, "PAY_2": 0, "PAY_3": 0, "PAY_4": 0, "PAY_5": 0, "PAY_6": 0,
                "BILL_AMT1": 2000, "BILL_AMT2": 2000, "BILL_AMT3": 2000, "BILL_AMT4": 2000,
                "BILL_AMT5": 2000, "BILL_AMT6": 2000, "PAY_AMT1": 1000, "PAY_AMT2": 1000,
                "PAY_AMT3": 1000, "PAY_AMT4": 1000, "PAY_AMT5": 1000, "PAY_AMT6": 1000,
            },
            seen={},
        )

    records = "\n".join(record.getMessage() for record in caplog.records)
    for secret in (ADMIN_PASSWORD, USER_PASSWORD, NEW_PASSWORD, token, fresh,
                   "definitely-not-the-password"):
        assert secret not in records
    assert "$argon2id$" not in records
    assert principal.username == "demo_user"


# ----------------------------------------------------- 7. XSRF and CORS stay on
def test_csrf_and_cors_protection_are_enabled_in_the_committed_config():
    config = (REPO / ".streamlit" / "config.toml").read_text(encoding="utf-8")
    assert "enableXsrfProtection = true" in config
    # CORS is DISABLED on purpose: the app is served single-origin behind Cloudflare
    # (www.aihubcampus.online). With enableCORS=true, Streamlit enforces its hardcoded
    # allowedOrigins list (which omits this domain) against the browser Origin header,
    # so the UI loads the shell but the session never establishes — blank screen forever.
    assert "enableCORS = false" in config
    for path in _shipped_files():
        if path.suffix == ".py":
            text = path.read_text(encoding="utf-8")
            assert "enableXsrfProtection" not in text
            assert "enableCORS" not in text
