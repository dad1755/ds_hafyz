"""Sprint 11: adversarial checks the happy-path suite would not notice.

Each test here attacks a specific boundary rather than re-asserting a feature:

1. **Role enforcement, swept.** Every privileged function in ``src.accounts`` and
   ``src.data_manager`` is called by an anonymous caller and by a signed-in *user*; each call
   must be refused, each user attempt must leave an ``auth.denied`` audit row, and the
   database must be unchanged afterwards. A single forgotten ``_admin()`` call fails this.
2. **Upload size, at the exact boundary.** The documented 10 MiB limit is checked by the
   code, and a payload of exactly ``max_bytes`` is accepted while one byte more is refused —
   an off-by-one in either direction fails.
3. **Quarantine containment.** An uploaded name is a label, never a path: a traversal name
   cannot escape the quarantine directory, the stored file is generated by the system and
   mode ``0600``.
4. **Secret patterns in the shipped tree.** The same regexes ``scripts/check_no_secrets.py``
   uses are applied to every file the image ships; no credential, key block or hash literal
   may appear.
5. **The database is not a static file.** Nothing enables Streamlit's static file serving and
   the SQLite path sits on the writable volume, so no request can fetch it.
6. **No credential in a log record.** A failed sign-in, a successful one, a password change
   and a prediction run with logging at ``DEBUG``: no password, token or hash may appear.
7. **XSRF and CORS stay enabled.** Both are asserted from the committed Streamlit config and
   from the absence of any code that turns them off.

Live-HTTP behaviour (websocket, headers through the tunnel, a 404 on ``/storage/*.db``) is
measured by ``evidence/s11/probe_http.py`` against the running deployment, because a unit
test cannot open a socket to it honestly.
"""

